#!/usr/bin/env python3
"""Generate a sonic-sairedis vslib lane map (lanemap.ini) from a SONiC port_config.ini.

Output format (see vslib/LaneMapFileParser.cpp):

    <ifname>:<lane>[,<lane>...]        one line per port, switch index 0 implied

ifname  = the SONiC port name (Ethernet0 ...). Only [A-Za-z0-9] are accepted by
          the parser and the name must be <= IFNAMSIZ (16) chars.
lanes   = the 'lanes' column of port_config.ini verbatim. On the AS5812-54T these
          are the Trident2+ physical port numbers (the right-hand side of the
          portmap_<logical>=<phys>:<speed> lines in the config.bcm). The number of
          lanes per port must be 1, 2, 4 or 8.

Optionally cross-checks every lane against the portmap in a config.bcm and
fails if a lane is not a physical port known to the SDK.

Usage:
    gen_lanemap.py port_config.ini [-c td2-as5812t-72x10G.config.bcm] [-o lanemap.ini]

Runs on the switch's host python3 as well (stdlib only, python >= 3.6).
"""

import argparse
import re
import sys

IFNAMSIZ = 16
VALID_LANE_COUNTS = (1, 2, 4, 8)
NAME_RE = re.compile(r"^[A-Za-z0-9]+$")
PORTMAP_RE = re.compile(r"^\s*portmap_(\d+)\s*=\s*(\d+)\s*:\s*(\d+)")


def parse_port_config(path):
    """Return a list of (name, [lanes]) in file order."""
    ports = []
    with open(path, encoding="utf-8") as fh:
        header = None
        for lineno, raw in enumerate(fh, 1):
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#"):
                # the header line is '# name lanes alias index speed ...'
                cols = line.lstrip("#").split()
                if cols and cols[0] == "name":
                    header = cols
                continue
            cols = line.split()
            if header is not None:
                try:
                    name_idx = header.index("name")
                    lanes_idx = header.index("lanes")
                except ValueError:
                    sys.exit("%s:%d: header has no 'name'/'lanes' column: %s" % (path, lineno, header))
            else:
                name_idx, lanes_idx = 0, 1
            if len(cols) <= max(name_idx, lanes_idx):
                sys.exit("%s:%d: too few columns: %r" % (path, lineno, line))
            name = cols[name_idx]
            lanes = cols[lanes_idx].split(",")
            if not NAME_RE.match(name) or len(name) > IFNAMSIZ:
                sys.exit("%s:%d: interface name %r is not acceptable to vslib (only [A-Za-z0-9], <= %d chars)"
                         % (path, lineno, name, IFNAMSIZ))
            if len(lanes) not in VALID_LANE_COUNTS:
                sys.exit("%s:%d: %s has %d lanes, vslib accepts 1/2/4/8" % (path, lineno, name, len(lanes)))
            try:
                lanes_int = [int(l) for l in lanes]
            except ValueError:
                sys.exit("%s:%d: non-numeric lane in %r" % (path, lineno, cols[lanes_idx]))
            ports.append((name, lanes_int))
    if not ports:
        sys.exit("%s: no ports found" % path)
    return ports


def parse_portmap(path):
    """Return {phys_port: logical_port} from portmap_<logical>=<phys>:<speed> lines."""
    phys_to_logical = {}
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            m = PORTMAP_RE.match(raw)
            if m:
                logical, phys = int(m.group(1)), int(m.group(2))
                phys_to_logical[phys] = logical
    if not phys_to_logical:
        sys.exit("%s: no portmap_ lines found" % path)
    return phys_to_logical


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("port_config", help="SONiC port_config.ini")
    ap.add_argument("-c", "--config-bcm", help="config.bcm to cross-check lanes against its portmap")
    ap.add_argument("-o", "--output", help="write here instead of stdout")
    args = ap.parse_args()

    ports = parse_port_config(args.port_config)

    # duplicate detection
    seen_names, seen_lanes = set(), {}
    for name, lanes in ports:
        if name in seen_names:
            sys.exit("duplicate port name %s" % name)
        seen_names.add(name)
        for l in lanes:
            if l in seen_lanes:
                sys.exit("lane %d used by both %s and %s" % (l, seen_lanes[l], name))
            seen_lanes[l] = name

    if args.config_bcm:
        phys_to_logical = parse_portmap(args.config_bcm)
        missing = [(n, l) for n, ls in ports for l in ls if l not in phys_to_logical]
        if missing:
            for n, l in missing:
                print("ERROR: %s lane %d is not a physical port in %s portmap" % (n, l, args.config_bcm), file=sys.stderr)
            sys.exit(1)

    out_lines = ["# generated by gen_lanemap.py from %s" % args.port_config,
                 "# format: <ifname>:<lane>[,<lane>...]  (vslib LaneMapFileParser, switch index 0)"]
    for name, lanes in ports:
        out_lines.append("%s:%s" % (name, ",".join(str(l) for l in lanes)))
    text = "\n".join(out_lines) + "\n"

    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote %d ports to %s" % (len(ports), args.output), file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
